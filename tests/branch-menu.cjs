const assert = require('node:assert/strict')
const crypto = require('node:crypto')
const { priceLines } = require('../dist/services/menuOptions')
const { catalogPrices } = require('../dist/services/branchMenu')
const { createMenuTemplate } = require('../dist/services/menuImport')

module.exports = async function ({ tx, db, api, base, token, org, org2, branch, dish, shift, table, signAccessToken, check }) {
 const second = await tx.branch.create({data:{organizationId:org.id,name:'Separate menu branch',code:'SEP'}})
 const variant = await tx.dish.create({data:{organizationId:org.id,categoryId:dish.categoryId,name:'Sized meal',price:20,shifts:{create:{shiftId:shift.id}},sizes:{create:[{name:'Small',price:20,isDefault:true},{name:'Large',price:35}]}}})
 const modifier=await tx.modifierGroup.create({data:{organizationId:org.id,name:'Branch extras',minSelect:0,maxSelect:1,options:{create:{name:'Extra sauce',price:2}}},include:{options:true}})
 await tx.dishModifierGroup.create({data:{dishId:variant.id,groupId:modifier.id}})
 const combo = await tx.dish.create({data:{organizationId:org.id,categoryId:dish.categoryId,name:'Branch combo',price:50,isCombo:true,shifts:{create:{shiftId:shift.id}},comboGroups:{create:{name:'Main',minSelect:1,maxSelect:1,options:{create:{dishId:dish.id,isDefault:true}}}}}})
 const path=b=>`/menu/branches/${b.id}/dishes`
 const list=async b=>{const r=await api('GET',path(b),undefined,true);assert.equal(r.status,200,JSON.stringify(r.data));return r.data.data}
 let a=await list(branch), b=await list(second)
 check('existing branch menus initialize with independent copies',()=>{assert.equal(a.find(d=>d.id===dish.id).price,116);assert.equal(b.find(d=>d.id===dish.id).price,116)})
 const save=async(br,d,patch={})=>api('PUT',`${path(br)}/${d.id}`,{price:d.price,isActive:d.isActive,optionPrices:Object.fromEntries(['sizes','modifiers','combo'].map(k=>[k,Object.fromEntries(d.priceOptions[k].map(o=>[o.id,o.price]))])),...patch},true)
 let r=await save(branch,a.find(d=>d.id===dish.id),{price:145.5})
 check('a branch can set its own price',()=>assert.equal(r.status,200,JSON.stringify(r.data)))
 const unchangedBranch=(await list(second)).find(d=>d.id===dish.id),unchangedCatalog=await tx.dish.findUnique({where:{id:dish.id}})
 check('other branch and shared catalog prices stay unchanged',()=>{assert.equal(unchangedBranch.price,116);assert.equal(unchangedCatalog.price,116)})
 const pos=await api('GET',`/pos/menu?branchId=${branch.id}`,undefined,true)
 const qr=await api('GET',`/public/tables/${table.orderToken}/menu`)
 const online=await api('GET',`/public/online/branches/${branch.id}/menu`)
 const find=(r,id)=>r.data.categories.flatMap(c=>c.dishes).find(d=>d.id===id)
 check('POS, QR and online menus display the branch price',()=>{for(const r of [pos,qr,online]){assert.equal(r.status,200,JSON.stringify(r.data));assert.equal(find(r,dish.id).price,145.5)}})
 const priced=await priceLines(db,{organizationId:org.id,branchId:branch.id,items:[{dishId:dish.id,quantity:2}]})
 check('server pricing uses branch price and quantity',()=>assert.equal(priced.lines[0].lineTotal,291))
 const postOnline=()=>api('POST',`/public/online/branches/${branch.id}/orders`,{requestId:crypto.randomUUID(),customerName:'Branch menu guest',customerPhone:'+923001234567',items:[{dishId:dish.id,quantity:1}]})
 r=await postOnline()
 check('online placement snapshots the branch price',()=>{assert.equal(r.status,201,JSON.stringify(r.data));assert.equal(r.data.order.items[0].unitPrice,145.5)})
 const orderId=r.data.order.id
 await save(branch,a.find(d=>d.id===dish.id),{price:150})
 const originalLine=await tx.customerOrderItem.findFirst({where:{orderId}})
 check('menu price changes do not reprice existing orders',()=>assert.equal(originalLine.unitPrice,145.5))
 await save(branch,a.find(d=>d.id===dish.id),{isActive:false})
 r=await api('GET',`/pos/menu?branchId=${branch.id}`,undefined,true)
 check('branch removal hides a dish from its POS',()=>assert.equal(find(r,dish.id),undefined))
 r=await postOnline()
 check('online order rejects a removed branch dish',()=>assert.equal(r.status,409,JSON.stringify(r.data)))
 r=await api('POST',`/public/tables/${table.orderToken}/orders`,{items:[{dishId:dish.id,quantity:1}]})
 check('QR order rejects a removed branch dish',()=>assert.equal(r.status,409,JSON.stringify(r.data)))
 const denied=await priceLines(db,{organizationId:org.id,branchId:branch.id,items:[{dishId:dish.id,quantity:1}]})
 check('POS, offline and call-center pricing reject branch removals',()=>assert.deepEqual(denied.unavailable,[dish.id]))
 r=await api('GET',`/pos/menu?branchId=${second.id}`,undefined,true)
 check('removing a dish does not hide it from another branch',()=>assert.equal(find(r,dish.id).price,116))
 const comboOpts=await tx.comboOption.findFirst({where:{group:{dishId:combo.id}}})
 await assert.rejects(()=>priceLines(db,{organizationId:org.id,branchId:branch.id,items:[{dishId:combo.id,quantity:1,combo:[{groupId:comboOpts.groupId,optionId:comboOpts.id}]}]}),/out of stock/)
 check('combos cannot bypass branch component availability',()=>{})
 const v=a.find(d=>d.id===variant.id), vp=Object.fromEntries(v.priceOptions.sizes.map(o=>[o.id,o.name==='Large'?48:27]))
 await save(branch,v,{optionPrices:{sizes:vp,modifiers:{[modifier.options[0].id]:5},combo:{}}})
 const small=v.priceOptions.sizes.find(o=>o.name==='Small')
 const sized=await priceLines(db,{organizationId:org.id,branchId:branch.id,items:[{dishId:variant.id,quantity:1,sizeId:small.id}]})
 check('size prices are branch-specific on the server',()=>assert.equal(sized.lines[0].unitPrice,27))
 const extra=await priceLines(db,{organizationId:org.id,branchId:branch.id,items:[{dishId:variant.id,quantity:1,sizeId:small.id,modifiers:[modifier.options[0].id]}]})
 check('modifier surcharges use independent branch prices',()=>assert.equal(extra.lines[0].unitPrice,32))
 assert.equal((await list(second)).find(d=>d.id===variant.id).priceOptions.sizes.find(s=>s.id===small.id).price,20)
 check('size price changes leave other branches unchanged',()=>{})
 const comboBody=await api('GET',`/menu/dishes/${combo.id}/options`,undefined,true)
 await api('PUT',`/menu/dishes/${combo.id}/options`,comboBody.data,true)
 const sameCombo=await tx.comboOption.findFirst({where:{group:{dishId:combo.id}}})
 check('saving combo definitions preserves option IDs and branch pricing references',()=>assert.equal(sameCombo.id,comboOpts.id))
 await api('PUT',`/menu/dishes/${dish.id}`,{price:999},true)
 check('catalog price edits do not overwrite branch prices',()=>{})
 assert.equal((await list(second)).find(d=>d.id===dish.id).price,116)
 const wb=createMenuTemplate();wb.getWorksheet('Dishes').getRow(2).values=['Test menu',dish.name,'',180,'All day',0,true,'Keep','']
 const upload=async(branchId,workbook=wb)=>{const form=new FormData();form.append('branchId',branchId);form.append('file',new Blob([await workbook.xlsx.writeBuffer()]),'menu.xlsx');const res=await fetch(base+'/menu/import',{method:'POST',headers:{Authorization:`Bearer ${token}`},body:form});return {status:res.status,data:await res.json()}}
 r=await upload(branch.id)
 check('Excel import updates only the selected branch',()=>assert.equal(r.status,200,JSON.stringify(r.data)))
 assert.equal((await list(branch)).find(d=>d.id===dish.id).price,180)
 assert.equal((await list(second)).find(d=>d.id===dish.id).price,116)
 assert.equal((await tx.dish.findUnique({where:{id:dish.id}})).price,999)
 wb.getWorksheet('Dishes').getRow(2).values=['Test menu','Only branch A','',70,'All day',0,true,'Keep','']
 r=await upload(branch.id)
 check('branch imports add new dishes without enabling other branches',()=>assert.equal(r.status,200,JSON.stringify(r.data)))
 const added=(await list(second)).find(d=>d.name==='Only branch A');assert.equal(added.isActive,false)
 wb.getWorksheet('Settings').addRow(['Asia/Riyadh']);r=await upload(branch.id)
 check('branch imports cannot silently change shared settings',()=>assert.equal(r.status,400))
 const foreign=await tx.branch.create({data:{organizationId:org2.id,name:'Foreign',code:'BRMENU'}})
 r=await api('GET',path(foreign),undefined,true)
 check('cross-organization branch menu reads are denied',()=>assert.equal(r.status,404))
 r=await save(foreign,a.find(d=>d.id===dish.id))
 check('cross-organization branch menu writes are denied',()=>assert.equal(r.status,404))
 r=await save(branch,v,{price:-1})
 check('negative branch prices are rejected',()=>assert.equal(r.status,400))
 r=await save(branch,v,{optionPrices:{sizes:{foreign:12},modifiers:{},combo:{}}})
 check('option IDs outside the dish are rejected',()=>assert.equal(r.status,400))
 const staff=await tx.user.create({data:{organizationId:org.id,email:'branch-menu-scoped@example.invalid',passwordHash:'unused',firstName:'Branch',lastName:'Manager'}})
 const role=await tx.role.create({data:{organizationId:org.id,name:'branch_menu_manager',displayName:'Branch menu manager',permissions:{create:{permission:{connect:{key:'can_manage_menu'}}}}}})
 await tx.userRole.create({data:{userId:staff.id,roleId:role.id}})
 await tx.userBranchAccess.create({data:{organizationId:org.id,userId:staff.id,branchId:branch.id}})
 const scoped=signAccessToken(staff.id,org.id,staff.email)
 r=await api('GET',path(second),undefined,scoped)
 check('branch-scoped managers cannot read another branch menu',()=>assert.equal(r.status,403))
 r=await api('PUT',`${path(second)}/${dish.id}`,{price:1,isActive:true,optionPrices:{sizes:{},modifiers:{},combo:{}}},scoped)
 check('branch-scoped managers cannot modify another branch menu',()=>assert.equal(r.status,403))
 r=await api('PUT',`/menu/dishes/${dish.id}`,{price:1},scoped)
 check('branch-scoped managers cannot alter the shared catalog',()=>assert.equal(r.status,403))
 const p=await catalogPrices(tx,org.id,variant.id)
 assert(p.sizes[small.id]===20)
}
