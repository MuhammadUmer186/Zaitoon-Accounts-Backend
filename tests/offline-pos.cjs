const assert = require('node:assert/strict')
const crypto = require('node:crypto')

module.exports = async ({ tx, api, signAccessToken, check }) => {
  const org = await tx.organization.create({ data: { name: 'Offline POS tests', foodCostMethod: 'recipes', requireTillForCash: true } })
  const branch = await tx.branch.create({ data: { organizationId: org.id, name: 'Offline counter', code: 'OFF', vatRate: 16 } })
  const user = await tx.user.create({ data: { organizationId: org.id, email: 'offline@example.invalid', firstName: 'Offline', lastName: 'Cashier', passwordHash: 'unused' } })
  const role = await tx.role.create({ data: { organizationId: org.id, name: 'super_admin', displayName: 'Offline test admin' } })
  await tx.userRole.create({ data: { userId: user.id, roleId: role.id } })
  const token = signAccessToken(user.id, org.id, user.email)
  const category = await tx.menuCategory.create({ data: { organizationId: org.id, name: 'Offline food' } })
  const dish = await tx.dish.create({ data: { organizationId: org.id, categoryId: category.id, name: 'Meal', price: 116 } })
  const item = await tx.item.create({ data: { organizationId: org.id, code: 'OFF', name: 'Offline ingredient', costPrice: 4 } })
  await tx.branchStock.create({ data: { organizationId: org.id, branchId: branch.id, itemId: item.id, quantityOnHand: 10, averageCost: 4, totalValue: 40 } })
  await tx.dishIngredient.create({ data: { dishId: dish.id, itemId: item.id, quantity: 0.5 } })
  const deviceId = crypto.randomUUID()
  const boot = () => api('POST', '/pos/offline/bootstrap', { deviceId, branchId: branch.id, name: 'Counter A' }, token)
  let r = await boot()
  check('offline bootstrap registers a device without exposing fiscal secrets', () => {
    assert.equal(r.status, 200, JSON.stringify(r.data)); assert.equal(r.data.prefix, 'D1'); assert.equal(r.data.till, null)
    for (const key of ['privateKey', 'privateKeySealed', 'productionToken', 'productionSecret']) assert.equal(r.data[key], undefined)
  })
  const noTill = r.data
  r = await api('POST', '/pos/tills', { branchId: branch.id, openingFloat: 500 }, token)
  const till = r.data
  r = await boot()
  const bootstrap = r.data
  check('bootstrap captures the open till and keeps device prefix stable', () => { assert.equal(r.status, 200); assert.equal(r.data.till.id, till.id); assert.equal(r.data.prefix, 'D1') })
  const secondDevice = await api('POST', '/pos/offline/bootstrap', { deviceId: crypto.randomUUID(), branchId: branch.id, name: 'Counter B' }, token)
  check('two devices get different number prefixes', () => assert.equal(secondDevice.data.prefix, 'D2'))
  const payload = (sequence, extra = {}) => {
    const at = new Date().toISOString()
    return { clientUuid: crypto.randomUUID(), deviceId, sequence, lease: bootstrap.lease, createdAt: at, orderType: 'takeaway', items: [{ dishId: dish.id, quantity: 1 }], expectedTotal: 116, vatRate: 16, ...extra }
  }
  const paid = (sequence, extra = {}) => {
    const b = payload(sequence, extra)
    return { ...b, payment: { paidAt: b.createdAt, payments: [{ method: 'cash', amount: 116 }], amountTendered: 120 } }
  }
  const sync = async (orders) => {
    const result = await api('POST', '/pos/orders/sync', { orders }, token)
    assert.equal(result.status, 200, JSON.stringify(result.data)); return result.data.results
  }
  const first = paid(1)
  let results = await sync([first])
  const serverOrder = results[0].order
  check('offline sync preserves timestamps and recomputes tax and payment', () => {
    assert.equal(results[0].status, 'synced', JSON.stringify(results)); assert.equal(serverOrder.status, 'completed'); assert.equal(serverOrder.totalAmount, 116)
    assert.equal(serverOrder.vatAmount, 16); assert.equal(serverOrder.offlineOrderNo, 'D1-000001'); assert.equal(serverOrder.createdAt, first.createdAt); assert.equal(serverOrder.closedAt, first.payment.paidAt); assert.equal(serverOrder.changeAmount, 4)
  })
  const event = await tx.tillPayment.findFirst({ where: { orderId: serverOrder.id } })
  check('synced cash links to the captured till at the original payment moment', () => { assert.equal(event.sessionId, till.id); assert.equal(event.createdAt.toISOString(), first.payment.paidAt) })
  results = await sync([first])
  const count = await tx.customerOrder.count({ where: { organizationId: org.id } })
  const paymentCount = await tx.tillPayment.count({ where: { orderId: serverOrder.id } })
  check('sync retries create no duplicate orders, payments or stock consumption', () => { assert.equal(results[0].duplicate, true); assert.equal(results[0].order.id, serverOrder.id); assert.equal(count, 1); assert.equal(paymentCount, 1) })
  results = await sync([{ ...first, items: [{ dishId: dish.id, quantity: 2 }] }])
  check('a reused UUID cannot replace an earlier order', () => assert.equal(results[0].code, 'OFFLINE_ID_CONFLICT'))
  results = await sync([{ ...first, payment: { ...first.payment, amountTendered: 999 } }])
  check('a replay cannot change the payment', () => assert.equal(results[0].code, 'OFFLINE_PAYMENT_CONFLICT'))
  results = await sync([paid(1)])
  check('a device sequence cannot be reused for another UUID', () => assert.equal(results[0].code, 'OFFLINE_NUMBER_CONFLICT'))
  const second = paid(1, { deviceId: secondDevice.data.deviceId, lease: secondDevice.data.lease })
  results = await sync([second])
  check('the same sequence on another device remains unique', () => { assert.equal(results[0].status, 'synced'); assert.equal(results[0].order.offlineOrderNo, 'D2-000001') })
  const bad = paid(3); bad.expectedTotal = 1
  const valid = payload(4)
  results = await sync([bad, valid])
  check('conflicts do not prevent other orders in a batch from syncing', () => { assert.equal(results[0].code, 'OFFLINE_PRICE_CHANGED'); assert.equal(results[1].status, 'synced'); assert.equal(results[1].order.status, 'open') })
  const orphan = await tx.offlineOrderSync.findUnique({ where: { organizationId_clientUuid: { organizationId: org.id, clientUuid: bad.clientUuid } } })
  check('a price conflict rolls back order and financial writes', () => assert.equal(orphan, null))
  const shortPayment = payload(19, { payment: { paidAt: new Date().toISOString(), payments: [{ method: 'cash', amount: 115 }] } })
  shortPayment.payment.paidAt = shortPayment.createdAt
  results = await sync([shortPayment])
  check('a recorded payment must still equal the authoritative bill', () => assert.equal(results[0].code, 'PAYMENT_MISMATCH'))
  const shortOrphan = await tx.offlineOrderSync.findUnique({ where: { organizationId_clientUuid: { organizationId: org.id, clientUuid: shortPayment.clientUuid } } })
  check('a payment mismatch leaves no partial synced order', () => assert.equal(shortOrphan, null))
  const withPayment = { ...valid, payment: { paidAt: new Date().toISOString(), payments: [{ method: 'cash', amount: 116 }] } }
  results = await sync([withPayment])
  check('an offline order synced unpaid can receive its recorded payment later', () => { assert.equal(results[0].status, 'synced', JSON.stringify(results)); assert.equal(results[0].order.status, 'completed') })
  const stock = await tx.branchStock.findUniqueOrThrow({ where: { branchId_itemId: { branchId: branch.id, itemId: item.id } } })
  check('all three paid offline orders consume stock exactly once', () => assert.equal(stock.quantityOnHand, 8.5))
  const future = payload(5, { createdAt: new Date(Date.now() + 600000).toISOString() })
  results = await sync([future])
  check('future device timestamps are refused', () => assert.equal(results[0].code, 'OFFLINE_TIME_CONFLICT'))
  results = await sync([payload(6, { lease: bootstrap.lease + 'tampered' })])
  check('tampered offline authorization is refused', () => assert.equal(results[0].code, 'OFFLINE_LEASE_INVALID'))
  results = await sync([paid(7, { lease: noTill.lease })])
  check('offline cash cannot bypass the captured till requirement', () => assert.equal(results[0].code, 'TILL_REQUIRED'))
  await tx.dish.update({ where: { id: dish.id }, data: { price: 120 } })
  results = await sync([payload(8)])
  check('changed menu prices require review rather than trusting cached prices', () => assert.equal(results[0].code, 'OFFLINE_PRICE_CHANGED'))
  await tx.dish.update({ where: { id: dish.id }, data: { price: 116 } })
  await tx.dishOutOfStock.create({ data: { organizationId: org.id, branchId: branch.id, dishId: dish.id, markedBy: user.id } })
  results = await sync([payload(9)])
  check('unavailable dishes remain unsynced for review', () => assert.equal(results[0].code, 'DISH_UNAVAILABLE'))
  await tx.dishOutOfStock.deleteMany({ where: { dishId: dish.id, branchId: branch.id } })
  await tx.branch.update({ where: { id: branch.id }, data: { vatRate: 15 } })
  results = await sync([payload(10)])
  check('tax-rate changes are returned as conflicts', () => assert.equal(results[0].code, 'OFFLINE_TAX_CHANGED'))
  await tx.branch.update({ where: { id: branch.id }, data: { vatRate: 16 } })
  const table = await tx.diningTable.create({ data: { organizationId: org.id, branchId: branch.id, name: 'Offline T1', orderToken: crypto.randomUUID(), reviewToken: crypto.randomUUID() } })
  await tx.customerOrder.create({ data: { organizationId: org.id, branchId: branch.id, tableId: table.id, orderNo: 9000 } })
  results = await sync([payload(11, { orderType: 'dine_in', tableId: table.id })])
  check('a table occupied while offline produces a conflict', () => assert.equal(results[0].code, 'OFFLINE_TABLE_CONFLICT'))
  const { config } = require('../dist/config')
  const jwt = require('jsonwebtoken')
  const oldIssued = Math.floor(Date.now() / 1000) - 25 * 3600
  const oldLease = jwt.sign({ purpose: 'pos-offline', organizationId: org.id, branchId: branch.id, userId: user.id, deviceId, tillSessionId: null, iat: oldIssued }, `${config.jwtSecret}:pos-offline`, { expiresIn: '24h', audience: 'pos-offline' })
  const oldTime = new Date((oldIssued + 3600) * 1000).toISOString()
  results = await sync([payload(14, { lease: oldLease, createdAt: oldTime, payment: { paidAt: oldTime, payments: [{ method: 'card', amount: 116 }] } })])
  check('an expired lease can still sync a sale recorded within its original validity', () => { assert.equal(results[0].status, 'synced', JSON.stringify(results)); assert.equal(results[0].order.closedAt, oldTime) })
  results = await sync([payload(15, { lease: oldLease })])
  check('an old lease cannot authorize sales recorded after it expired', () => assert.equal(results[0].code, 'OFFLINE_TIME_CONFLICT'))
  const stranger = await tx.user.create({ data: { organizationId: org.id, email: 'offline-other@example.invalid', firstName: 'Other', lastName: 'Cashier', passwordHash: 'unused' } })
  await tx.userRole.create({ data: { userId: stranger.id, roleId: role.id } })
  r = await api('POST', '/pos/orders/sync', { orders: [payload(16)] }, signAccessToken(stranger.id, org.id, stranger.email))
  check('another cashier cannot replay the original cashier’s lease', () => assert.equal(r.data.results[0].code, 'OFFLINE_OWNER'))
  await tx.posOfflineDevice.update({ where: { id: deviceId }, data: { isActive: false } })
  results = await sync([payload(17)])
  check('a disabled device cannot sync another sale', () => assert.equal(results[0].code, 'OFFLINE_DEVICE_INVALID'))
  await tx.posOfflineDevice.update({ where: { id: deviceId }, data: { isActive: true } })
  await tx.dish.update({ where: { id: dish.id }, data: { price: 0 } })
  const free = payload(18, { expectedTotal: 0, payment: { paidAt: new Date().toISOString(), payments: [{ method: 'card', amount: 0 }] } })
  // One captured instant prevents a millisecond ordering race in the fixture.
  free.payment.paidAt = free.createdAt
  results = await sync([free])
  check('a zero-price offline order completes without inventing a payment amount', () => { assert.equal(results[0].status, 'synced', JSON.stringify(results)); assert.equal(results[0].order.totalAmount, 0) })
  await tx.dish.update({ where: { id: dish.id }, data: { price: 116 } })
  await tx.tillSession.update({ where: { id: till.id }, data: { status: 'closed', closedAt: new Date() } })
  results = await sync([paid(12)])
  check('sync does not mutate a till that was closed during the outage', () => assert.equal(results[0].code, 'OFFLINE_TILL_CLOSED'))
  const denied = await tx.user.create({ data: { organizationId: org.id, email: 'offline-denied@example.invalid', firstName: 'Denied', lastName: 'User', passwordHash: 'unused' } })
  r = await api('POST', '/pos/orders/sync', { orders: [first] }, signAccessToken(denied.id, org.id, denied.email))
  check('sync requires current POS permission', () => assert.equal(r.status, 403))
  const cashierRole = await tx.role.create({ data: { organizationId: org.id, name: 'offline_order_taker', displayName: 'Order taker' } })
  const posPermission = await tx.permission.findUniqueOrThrow({ where: { key: 'can_use_pos' } })
  await tx.rolePermission.create({ data: { roleId: cashierRole.id, permissionId: posPermission.id } })
  await tx.userRole.create({ data: { userId: denied.id, roleId: cashierRole.id } })
  const orderTakerToken = signAccessToken(denied.id, org.id, denied.email)
  const orderTakerBoot = await api('POST', '/pos/offline/bootstrap', { deviceId: crypto.randomUUID(), branchId: branch.id, name: 'Order taker' }, orderTakerToken)
  const restricted = paid(20, { deviceId: orderTakerBoot.data.deviceId, lease: orderTakerBoot.data.lease })
  r = await api('POST', '/pos/orders/sync', { orders: [restricted] }, orderTakerToken)
  check('an order-only cashier cannot sync a payment without order-management permission', () => assert.equal(r.data.results[0].code, 'FORBIDDEN'))
  // Toggle policy is enforced server-side and must not strand old receipts.
  const savedBeforeDisable = payload(41, { createdAt: new Date(Date.now() - 10).toISOString() })
  const paidBeforeDisable = paid(45, { createdAt: savedBeforeDisable.createdAt, lease: noTill.lease })
  paidBeforeDisable.payment = { paidAt: savedBeforeDisable.createdAt, payments: [{ method: 'card', amount: 116 }] }
  r = await api('PUT', `/orgs/${org.id}`, { offlinePosEnabled: false }, orderTakerToken)
  check('ordinary POS staff cannot change offline policy', () => assert.equal(r.status, 403))
  r = await api('PUT', `/orgs/${org.id}`, { offlinePosEnabled: 'false' }, token)
  check('offline toggle rejects non-boolean settings', () => assert.equal(r.status, 400))
  r = await api('PUT', `/orgs/${org.id}`, { offlinePosEnabled: false }, token)
  const cutoff = Date.parse(r.data.offlinePosDisabledAt)
  check('administrator can disable offline functionality', () => { assert.equal(r.status, 200); assert.equal(r.data.offlinePosEnabled, false); assert.ok(Number.isFinite(cutoff)) })
  const disabledAgain = await api('PUT', `/orgs/${org.id}`, { offlinePosEnabled: false }, token)
  check('repeated disable preserves the original receipt cutoff', () => assert.equal(disabledAgain.data.offlinePosDisabledAt, r.data.offlinePosDisabledAt))
  r = await boot()
  check('disabled offline functionality blocks bootstrap', () => { assert.equal(r.status, 403); assert.equal(r.data.code, 'OFFLINE_DISABLED') })
  results = await sync([savedBeforeDisable])
  check('unpaid tickets captured before disable still sync', () => assert.equal(results[0].status, 'synced', JSON.stringify(results)))
  results = await sync([paidBeforeDisable])
  check('paid receipts captured before disable still sync without losing payment', () => { assert.equal(results[0].status, 'synced', JSON.stringify(results)); assert.equal(results[0].order.status, 'completed') })
  results = await sync([first])
  check('disabling does not break idempotent receipt recovery', () => { assert.equal(results[0].status, 'synced'); assert.equal(results[0].duplicate, true) })
  const afterCutoff = new Date(cutoff + 5).toISOString()
  results = await sync([payload(42, { createdAt: afterCutoff })])
  check('old authorizations cannot create orders after disable', () => assert.equal(results[0].code, 'OFFLINE_DISABLED'))
  results = await sync([{ ...savedBeforeDisable, payment: { paidAt: afterCutoff, payments: [{ method: 'card', amount: 116 }] } }])
  check('old tickets cannot take a new offline payment after disable', () => assert.equal(results[0].code, 'OFFLINE_DISABLED'))
  r = await api('PUT', `/orgs/${org.id}`, { offlinePosEnabled: true }, token)
  check('administrator can re-enable offline functionality', () => { assert.equal(r.status, 200); assert.equal(r.data.offlinePosEnabled, true); assert.ok(r.data.offlinePosDisabledAt) })
  results = await sync([payload(43, { createdAt: afterCutoff })])
  check('re-enabling does not reactivate leases from before disable', () => assert.equal(results[0].code, 'OFFLINE_DISABLED'))
  const renewed = await boot()
  check('re-enabled devices can obtain fresh authorization', () => assert.equal(renewed.status, 200, JSON.stringify(renewed.data)))
  const renewalAt = new Date(Math.max(Date.now(), cutoff + 10)).toISOString()
  results = await sync([payload(44, { lease: renewed.data.lease, createdAt: renewalAt })])
  check('fresh authorization allows offline orders after re-enable', () => assert.equal(results[0].status, 'synced', JSON.stringify(results)))
  await api('PUT', `/orgs/${org.id}`, { offlinePosEnabled: false }, token)
  await api('PUT', `/orgs/${org.id}`, { offlinePosEnabled: true }, token)
  results = await sync([payload(46, { createdAt: afterCutoff })])
  check('multiple toggle cycles never revive an older revoked authorization', () => assert.equal(results[0].code, 'OFFLINE_DISABLED'))
  await tx.branch.update({ where: { id: branch.id }, data: { isActive: false } })
}
