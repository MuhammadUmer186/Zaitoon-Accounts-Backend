// Real HTTP and scratch PostgreSQL only. No real printer or production orders.
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const { createScratch } = require('./scratch-db.cjs');
let scratch, db, appDb, server, passed = 0;
const check = (name, run) => { run(); passed++; console.log('PASS ' + name); };
(async () => {
  scratch = await createScratch();
  process.env.DATABASE_URL = scratch.url;
  delete process.env.FOODSYNC_DEPLOYMENT_MODE;
  delete process.env.KITCHEN_PRINTERS_JSON;
  db = scratch.client();
  const org = await db.organization.create({ data: { name: 'Cloud printer QA' } });
  const otherOrg = await db.organization.create({ data: { name: 'Other printer tenant' } });
  const branch = await db.branch.create({ data: { organizationId: org.id, name: 'Online branch', code: 'C' } });
  const otherBranch = await db.branch.create({ data: { organizationId: otherOrg.id, name: 'Other branch', code: 'C' } });
  const category = await db.menuCategory.create({ data: { organizationId: org.id, name: 'Meals' } });
  const dish = await db.dish.create({ data: { organizationId: org.id, categoryId: category.id, name: 'Meal', price: 10 } });
  const station = await db.kitchenStation.create({ data: { organizationId: org.id, name: 'Grill' } });
  const p = { id: 'cloud-grill', organizationId: org.id, branchId: branch.id, stationId: station.id, key: crypto.randomBytes(32).toString('hex'), enabledAt: new Date(Date.now() - 60000).toISOString() };
  const other = { ...p, id: 'cloud-other', organizationId: otherOrg.id, branchId: otherBranch.id, stationId: 'none', key: crypto.randomBytes(32).toString('hex') };
  process.env.KITCHEN_CLOUD_PRINTERS_JSON = JSON.stringify([p, other]);
  const { execFileSync } = require('node:child_process');
  const setupFile = require('node:path').resolve(__dirname, '../scripts/cloud-printer-setup.cjs');
  const listed = JSON.parse(execFileSync(process.execPath, [setupFile, '--list'], { env: { ...process.env }, encoding: 'utf8' }));
  check('container setup helper lists actual branch and station IDs without changing records', () => { assert.ok(listed.branches.some(b => b.id === branch.id)); assert.ok(listed.stations.some(s => s.id === station.id)); });
  const setup = execFileSync(process.execPath, [setupFile, '--branch-id', branch.id, '--station-id', station.id, '--portal', 'https://staff.example.invalid'], { env: { ...process.env, KITCHEN_CLOUD_PRINTERS_JSON: '[]' }, encoding: 'utf8' });
  const generated = JSON.parse(setup.split('\n').find(line => line.startsWith('KITCHEN_CLOUD_PRINTERS_JSON=')).split('=').slice(1).join('='))[0];
  check('setup helper generates matching private server and firmware settings for the selected branch', () => { assert.equal(generated.branchId, branch.id); assert.equal(generated.stationId, station.id); assert.match(generated.key, /^[a-f0-9]{64}$/); assert.ok(setup.includes(`#define FOODSYNC_PRINT_KEY "${generated.key}"`)); });
  const service = require('../dist/services/cloudKitchenPrinting');
  const { automaticKitchenStations } = require('../dist/services/kitchenPrinting');
  const app = require('../dist/app').default;
  appDb = require('../dist/config').prisma;
  server = await new Promise(resolve => { const listener = app.listen(0, '127.0.0.1', () => resolve(listener)); });
  const base = `http://127.0.0.1:${server.address().port}/api/v1/printer-device`;
  const request = (printer = p, suffix = 'poll', body = {}, key = printer.key) => fetch(`${base}/${printer.id}/${suffix}`, { method: 'POST', headers: { Authorization: 'Bearer ' + key, 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  const poll = async (printer = p) => {
    const response = await request(printer);
    const frame = Buffer.from(await response.arrayBuffer());
    return { response, frame };
  };
  const decode = frame => {
    const end = frame.indexOf(10), header = frame.subarray(0, end).toString().split(' '), bytes = frame.subarray(end + 1);
    const [version, sequence, jobId, length, digest, mac] = header;
    assert.equal(version, 'FS1'); assert.equal(bytes.length, Number(length));
    assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'), digest);
    assert.equal(crypto.createHmac('sha256', p.key).update(`${sequence}:${jobId}:${length}:${digest}`).digest('hex'), mac);
    return { sequence, jobId, digest, bytes };
  };
  const ack = (job, reply = `OK ${job.jobId}`) => ({ jobId: job.jobId, sequence: job.sequence, reply, signature: crypto.createHmac('sha256', p.key).update(`ACK:${job.sequence}:${job.jobId}:${job.digest}:${reply}`).digest('hex') });
  let number = 0;
  const order = (status = 'completed', overrides = {}) => db.customerOrder.create({ data: { organizationId: org.id, branchId: branch.id, orderNo: ++number, orderType: 'takeaway', source: 'online', status, ...(status === 'completed' && { closedAt: new Date() }), subtotal: 10, itemsTotal: 10, totalAmount: 10, items: { create: [{ dishId: dish.id, dishName: 'Meal', quantity: 1, unitPrice: 10, lineTotal: 10, status: 'pending', stationId: station.id, ...overrides }] } }, include: { items: true } });
  check('valid cloud configuration loads without a local branch runtime', () => assert.equal(service.readCloudKitchenPrinters().length, 2));
  process.env.KITCHEN_CLOUD_PRINTERS_JSON = JSON.stringify([p, p]);
  check('duplicate identities and station routes are rejected', () => assert.throws(service.readCloudKitchenPrinters));
  process.env.KITCHEN_CLOUD_PRINTERS_JSON = JSON.stringify([p, other]);
  let response = await request(p, 'poll', {}, 'f'.repeat(64));
  check('wrong device key is rejected', () => assert.equal(response.status, 401));
  response = await request({ ...p, id: 'cloud-unknown' });
  check('unknown device is rejected', () => assert.equal(response.status, 401));
  await order('open');
  await order('completed', { held: true, course: 2 });
  let result = await poll();
  check('unpaid orders and held courses never print', () => assert.equal(result.response.status, 204));
  const paid = await order();
  result = await poll();
  const first = decode(result.frame);
  check('paid online order returns authenticated binary ESC/POS frame', () => { assert.equal(result.response.status, 200); assert.ok(first.bytes.includes(Buffer.from('ORDER #' + paid.orderNo))); assert.equal(result.response.headers.get('cache-control'), 'no-store'); });
  check('proxy-safe frame length matches the complete binary payload', () => assert.equal(Number(result.response.headers.get('x-foodsync-frame-length')), result.frame.length));
  response = await request(p, 'ack', { ...ack(first), sequence: 'not-a-number' });
  check('malformed sequence is rejected as validation error', () => assert.equal(response.status, 400));
  const concurrent = await Promise.all([poll(), poll()]);
  check('lost downloads and concurrent polls return exactly the same job and sequence', () => concurrent.forEach(r => assert.ok(r.frame.equals(result.frame))));
  const automatic = await automaticKitchenStations(org.id, branch.id);
  check('cloud routing prevents a browser from also printing the same station', () => assert.deepEqual(automatic, [station.id]));
  const foreign = await poll(other);
  check('another tenant cannot read this station queue', () => assert.equal(foreign.response.status, 204));
  response = await request(other, 'ack', ack(first));
  check('another device cannot acknowledge this job', () => assert.equal(response.status, 404));
  response = await request(p, 'ack', { ...ack(first), signature: '0'.repeat(64) });
  check('forged acknowledgement cannot mark a job delivered', () => assert.equal(response.status, 401));
  response = await request(p, 'ack', ack(first, 'ERROR NOT_READY'));
  check('printer not ready is explicitly queued for retry', () => assert.equal(response.status, 200));
  result = await poll();
  check('a ready retry preserves the device sequence', () => assert.equal(decode(result.frame).sequence, first.sequence));
  response = await request(p, 'ack', ack(first));
  check('authenticated USB completion is recorded', () => assert.equal(response.status, 200));
  response = await request(p, 'ack', ack(first));
  check('lost acknowledgement responses can be retried idempotently', () => assert.equal(response.status, 200));
  result = await poll();
  check('completed tickets are not offered again', () => assert.equal(result.response.status, 204));
  const held = await db.customerOrderItem.findFirst({ where: { held: true } });
  await db.customerOrderItem.update({ where: { id: held.id }, data: { held: false, firedAt: new Date() } });
  result = await poll();
  const released = decode(result.frame);
  check('fired held courses receive a new job', () => assert.notEqual(released.jobId, first.jobId));
  response = await request(p, 'ack', ack(released, 'UNCERTAIN ' + released.jobId));
  check('uncertain USB delivery is held for physical review', () => assert.equal(response.status, 200));
  await order();
  result = await poll();
  check('held uncertainty blocks further automatic output', () => assert.equal(result.response.status, 409));
  await db.kitchenPrintJob.update({ where: { id: released.jobId }, data: { state: 'discarded' } });
  response = await request(p, 'ack', ack(released));
  check('late acknowledgements cannot override an operator resolution', () => assert.equal(response.status, 409));
  await db.customerOrderItem.update({ where: { id: paid.items[0].id }, data: { status: 'cancelled' } });
  result = await poll();
  let pending = decode(result.frame);
  await request(p, 'ack', ack(pending));
  result = await poll();
  pending = decode(result.frame);
  check('cancelling a previously printed item generates a cancellation slip', () => assert.ok(pending.bytes.includes(Buffer.from('CANCEL - DO NOT PREPARE'))));
  await request(p, 'ack', ack(pending));
  await db.branchSyncNode.create({ data: { organizationId: org.id, branchId: branch.id, name: 'PC owner', tokenHash: crypto.randomBytes(32).toString('hex') } });
  result = await poll();
  check('cloud printing is refused when a branch PC owns the branch', () => assert.equal(result.response.status, 409));
  await db.branchSyncNode.deleteMany();
  process.env.FOODSYNC_DEPLOYMENT_MODE = 'branch';
  result = await poll();
  check('branch-mode deployments cannot run the cloud device endpoint', () => assert.equal(result.response.status, 409));
  console.log(`${passed} direct-cloud printer checks passed.`);
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  if (server) await new Promise(resolve => server.close(resolve));
  if (appDb) await appDb.$disconnect();
  if (db) await db.$disconnect();
  if (scratch) await scratch.drop();
});
