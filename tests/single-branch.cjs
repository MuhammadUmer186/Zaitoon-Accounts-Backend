const assert = require('node:assert/strict')

module.exports = async function singleBranchTests({ tx, api, base, token, org, branch, table, check }) {
  const { restaurantPresentation } = require('../dist/utils/restaurantPresentation')
  const original = { branch: { id: branch.id, name: branch.name }, amount: 42, when: new Date(), oldData: { branchName: branch.name } }
  const shown = restaurantPresentation(original, 'Test Restaurant')
  check('restaurant presentation preserves IDs, money, dates and audit history', () => {
    assert.equal(shown.branch.id, branch.id); assert.equal(shown.branch.name, 'Test Restaurant')
    assert.equal(shown.amount, 42); assert.equal(shown.when, original.when); assert.equal(shown.oldData.branchName, branch.name)
    assert.equal(original.branch.name, branch.name)
  })
  const extra = await tx.branch.create({ data: { organizationId: org.id, name: 'Second outlet', code: 'SECOND' } })
  let r = await api('PUT', `/orgs/${org.id}`, { multiBranch: false }, true)
  check('single-branch setting rejects multiple active locations', () => assert.equal(r.status, 400))
  await tx.branch.update({ where: { id: extra.id }, data: { isActive: false } })
  await tx.branch.update({ where: { id: branch.id }, data: { isActive: false } })
  r = await api('PUT', `/orgs/${org.id}`, { multiBranch: false }, true)
  check('single-branch setting rejects zero active locations', () => assert.equal(r.status, 400))
  await tx.branch.update({ where: { id: branch.id }, data: { isActive: true } })
  await tx.organization.update({ where: { id: org.id }, data: { tradeName: 'Test Restaurant' } })
  r = await api('PUT', `/orgs/${org.id}`, { multiBranch: false }, true)
  check('single-branch mode enabled with one active location', () => { assert.equal(r.status, 200); assert.equal(r.data.multiBranch, false) })
  r = await api('GET', '/public/online/branches')
  check('public menu returns automatic restaurant context', () => { assert.equal(r.data.multiBranch, false); assert.equal(r.data.branches.length, 1); assert.equal(r.data.branches[0].name, 'Test Restaurant'); assert.equal(r.data.branches[0].id, branch.id) })
  r = await api('GET', `/public/online/branches/${branch.id}/menu`)
  check('public menu uses restaurant identity and hides multi-branch navigation', () => { assert.equal(r.data.restaurant.multiBranch, false); assert.equal(r.data.branch.name, 'Test Restaurant') })
  r = await api('GET', `/public/tables/${table.orderToken}/menu`)
  check('QR menu uses restaurant identity', () => { assert.equal(r.status, 200, JSON.stringify(r.data)); assert.equal(r.data.branch.name, 'Test Restaurant') })
  r = await api('GET', '/auth/me', undefined, true)
  check('staff branch context retains ID and uses restaurant name', () => { assert.equal(r.data.branches[0].id, branch.id); assert.equal(r.data.branches[0].name, 'Test Restaurant') })
  r = await api('GET', `/tables?branchId=${branch.id}`, undefined, true)
  check('staff table and QR data uses restaurant name', () => assert.equal(r.data.data[0].branch.name, 'Test Restaurant'))
  r = await api('GET', `/branches/${branch.id}`, undefined, true)
  check('stored branch configuration name remains unchanged', () => assert.equal(r.data.name, branch.name))
  r = await api('PUT', `/branches/${branch.id}`, { isActive: false }, true)
  check('single restaurant cannot lose its only active location', () => assert.equal(r.status, 400))
  const csv = await fetch(base + '/reports/general-ledger?format=csv', { headers: { Authorization: `Bearer ${token}` } })
  const csvText = await csv.text()
  check('ledger export labels the restaurant without changing totals', () => {
    assert.equal(csv.status, 200); assert.ok(csvText.replace(/^﻿/, '').startsWith('Report,General Ledger'))
    assert.ok(csvText.includes('\r\nScope,Test Restaurant\r\n')); assert.ok(csvText.includes('Date,Entry no.,Description,Debit (PKR),Credit (PKR),Balance (PKR)'))
    assert.ok(!csvText.includes('Branch,')); assert.ok(/\r\nTOTAL,,,[\d.]+,[\d.]+,/.test(csvText))
  })
  const template = await fetch(base + '/purchasing/import/template', { headers: { Authorization: `Bearer ${token}` } })
  check('single restaurant purchase template needs no branch column', () => assert.equal(template.status, 200))
  assert.ok(!(await template.text()).includes('branchName'))
  const form = new FormData()
  form.append('file', new Blob(['supplierName,supplyDate,paymentType,itemDescription,quantity,unitCost\nSample supplier,2026-10-12,cash,Food,1,100\n'], { type: 'text/csv' }), 'purchases.csv')
  const validation = await fetch(base + '/purchasing/import/validate', { method: 'POST', headers: { Authorization: `Bearer ${token}` }, body: form })
  const parsed = await validation.json()
  check('purchase import resolves restaurant automatically', () => { assert.equal(validation.status, 200); assert.equal(parsed.invalidRows, 0, JSON.stringify(parsed)); assert.equal(parsed.rows[0].data.branchName, 'Test Restaurant') })
  r = await api('PUT', `/orgs/${org.id}`, { multiBranch: true }, true)
  check('multi-branch mode can be re-enabled', () => assert.equal(r.status, 200))
  r = await api('GET', '/auth/me', undefined, true)
  check('multi-branch mode restores original branch labels', () => assert.equal(r.data.branches[0].name, branch.name))
  r = await api('GET', '/public/online/branches')
  check('public branch chooser returns in multi-branch mode', () => { assert.equal(r.data.multiBranch, true); assert.equal(r.data.branches[0].name, branch.name) })
}
